// Photo files: normalized with sharp, then stored per site.
// Local dev writes to disk and serves signed URLs from this API. Azure uses one private Blob
// container per site (optionally one storage account per site) and hands out short-lived SAS URLs.
import { BlobServiceClient, BlobSASPermissions, generateBlobSASQueryParameters, StorageSharedKeyCredential } from '@azure/storage-blob';
import type { PhotoStore, Site } from '@whatbox/core';
import { RuleError } from '@whatbox/core';
import { createHmac, timingSafeEqual } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, normalize } from 'node:path';
import sharp from 'sharp';
import { config } from './config';

const MAX_EDGE = 1600;
const URL_TTL_S = 3600;

// Re-encode every upload: checks it really is an image, applies EXIF rotation, strips all
// metadata (GPS location included), and caps the size.
export async function normalizeImage(input: Buffer): Promise<{ data: Buffer; contentType: string }> {
  let meta: sharp.Metadata;
  try {
    meta = await sharp(input, { limitInputPixels: 50_000_000 }).metadata();
  } catch {
    throw new RuleError('not_an_image', 'That file is not a photo we can read. Try a JPEG, PNG, WebP or HEIC.', 415);
  }
  if (!meta.format || !['jpeg', 'png', 'webp', 'heif', 'avif', 'gif'].includes(meta.format)) {
    throw new RuleError('not_an_image', 'That file type is not supported. Try a JPEG, PNG or WebP.', 415);
  }
  const data = await sharp(input, { limitInputPixels: 50_000_000 })
    .rotate()
    .resize({ width: MAX_EDGE, height: MAX_EDGE, fit: 'inside', withoutEnlargement: true })
    .jpeg({ quality: 82, mozjpeg: true })
    .toBuffer();
  return { data, contentType: 'image/jpeg' };
}

// Keys look like "<memberId>/<photoId>", generated by the core. Anything else is refused.
const KEY_RE = /^[A-Za-z0-9_-]+\/[A-Za-z0-9_-]+$/;
function checkKey(key: string) {
  if (!KEY_RE.test(key)) throw new Error('Bad photo key');
}

// Rounding the expiry to the hour keeps URLs stable within an hour, so browsers and the CDN can cache them.
function expiryEpoch() {
  const now = Math.floor(Date.now() / 1000);
  return (Math.floor(now / URL_TTL_S) + 2) * URL_TTL_S;
}

export class LocalPhotoStore implements PhotoStore {
  constructor(private dir: string, private publicBase: string, private secret: string) {}
  private path(slug: string, key: string) {
    checkKey(key);
    const p = normalize(join(this.dir, slug, key + '.jpg'));
    if (!p.startsWith(normalize(this.dir))) throw new Error('Bad path');
    return p;
  }
  sign(slug: string, key: string, exp: number) {
    return createHmac('sha256', this.secret).update(`${slug}/${key}/${exp}`).digest('base64url');
  }
  async put(site: Site, key: string, data: Uint8Array) {
    const p = this.path(site.slug, key);
    await mkdir(dirname(p), { recursive: true });
    await writeFile(p, data);
  }
  async delete(site: Site, key: string) { await rm(this.path(site.slug, key), { force: true }); }
  readUrl(site: Site, key: string) {
    const exp = expiryEpoch();
    return `${this.publicBase}/files/${site.slug}/${key}?e=${exp}&s=${this.sign(site.slug, key, exp)}`;
  }
  // Used by the /files route.
  async read(slug: string, key: string, exp: number, sig: string): Promise<Buffer | null> {
    if (!/^[a-z0-9-]+$/.test(slug) || !KEY_RE.test(key) || !(exp > Date.now() / 1000)) return null;
    const want = Buffer.from(this.sign(slug, key, exp));
    const got = Buffer.from(sig);
    if (want.length !== got.length || !timingSafeEqual(want, got)) return null;
    try { return await readFile(this.path(slug, key)); } catch { return null; }
  }
}

interface AzureAccount { account: string; key: string }

export class AzureBlobPhotoStore implements PhotoStore {
  private clients = new Map<string, { svc: BlobServiceClient; cred: StorageSharedKeyCredential }>();
  private ready = new Set<string>();
  // perSite: optional {"site_afterh": {"account": "...", "key": "..."}} for a storage account per site.
  constructor(private fallback: AzureAccount | null, private perSite: Record<string, AzureAccount>) {}

  private client(site: Site) {
    const acct = this.perSite[site.id] ?? this.fallback;
    if (!acct) throw new Error(`No storage account configured for ${site.id}`);
    let c = this.clients.get(acct.account);
    if (!c) {
      const cred = new StorageSharedKeyCredential(acct.account, acct.key);
      c = { svc: new BlobServiceClient(`https://${acct.account}.blob.core.windows.net`, cred), cred };
      this.clients.set(acct.account, c);
    }
    return c;
  }
  private container(site: Site) { return `photos-${site.slug}`; }

  async put(site: Site, key: string, data: Uint8Array, contentType: string) {
    checkKey(key);
    const { svc } = this.client(site);
    const cont = svc.getContainerClient(this.container(site));
    if (!this.ready.has(site.id)) {
      await cont.createIfNotExists(); // private: no public access level
      this.ready.add(site.id);
    }
    await cont.getBlockBlobClient(key + '.jpg').uploadData(data, {
      blobHTTPHeaders: { blobContentType: contentType, blobCacheControl: 'private, max-age=3600' },
    });
  }
  async delete(site: Site, key: string) {
    checkKey(key);
    const { svc } = this.client(site);
    await svc.getContainerClient(this.container(site)).getBlockBlobClient(key + '.jpg').deleteIfExists();
  }
  readUrl(site: Site, key: string) {
    checkKey(key);
    const { svc, cred } = this.client(site);
    const blobName = key + '.jpg';
    const sas = generateBlobSASQueryParameters({
      containerName: this.container(site), blobName, permissions: BlobSASPermissions.parse('r'),
      expiresOn: new Date(expiryEpoch() * 1000), protocol: 'https' as never,
    }, cred).toString();
    // Build from the blob client: svc.url ends in "/", and a doubled slash makes Azure reject the URL.
    return `${svc.getContainerClient(this.container(site)).getBlobClient(blobName).url}?${sas}`;
  }
}

export function createPhotoStore(): PhotoStore | undefined {
  if (config.photoStore === 'azure') {
    const fallback = config.azureStorageAccount ? { account: config.azureStorageAccount, key: config.azureStorageKey } : null;
    return new AzureBlobPhotoStore(fallback, config.azureStorageJson ? JSON.parse(config.azureStorageJson) : {});
  }
  if (config.photoStore === 'local') {
    const secret = config.fileUrlSecret || config.devMasterKey;
    if (!secret) throw new Error('Set FILE_URL_SECRET for local photo storage.');
    return new LocalPhotoStore(config.photoDir, config.publicApiUrl, secret);
  }
  return undefined; // 'inline': prototype data URIs, never in production
}
